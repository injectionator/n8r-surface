import {build} from 'esbuild';
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {dirname,join} from 'node:path';
const packages=new Set();
for (const [source,name] of [['src/skill-artifacts-cli.ts','artifacts'],['src/skill-cyclonedx.ts','cyclonedx']]) {
 const file=`plugins/n8r-surface/skills/research/scripts/${name}.mjs`;
 const result=await build({entryPoints:[source],bundle:true,platform:'node',format:'esm',target:'node22',write:false,metafile:true,legalComments:'inline',banner:{js:'// Generated by scripts/build-skill.mjs. Do not edit. See THIRD-PARTY-NOTICES.txt.\nimport {createRequire} from "node:module"; const require = createRequire(import.meta.url);'}});
 for(const input of Object.keys(result.metafile.inputs)) {
  if(!input.startsWith('node_modules/'))continue;
  let directory=dirname(input);
  while(directory!=='.'&&!existsSync(join(directory,'package.json')))directory=dirname(directory);
  if(directory!=='.')packages.add(directory);
 }
 const bytes=result.outputFiles[0].contents;
 if(process.argv.includes('--check')){
  if(!readFileSync(file).equals(Buffer.from(bytes)))throw Error('Stale standalone skill bundle; run npm run build:skill');
 }else writeFileSync(file,bytes);
}

let notices='Bundled third-party code and schemas\n\nCycloneDX 1.7 schemas: OWASP Foundation / CycloneDX contributors, Apache-2.0.\nSource commit 4b3f59453366e27c8073fd24e98bf21ef8892c8e. See bundled LICENSE for Apache-2.0 terms.\n\n';
for(const directory of [...packages].sort()) {
 const pkg=JSON.parse(readFileSync(join(directory,'package.json'),'utf8'));
 const license=['LICENSE','LICENSE.md','LICENSE.txt','LICENSE-MIT','license','license.md','License.txt'].map(n=>join(directory,n)).find(existsSync) ?? (pkg.name==='schemes'?join(directory,'README.md'):undefined);
 if(!license)throw Error(`Missing bundled license: ${pkg.name}`);
 notices+=`${pkg.name} ${pkg.version} (${pkg.license})\n${pkg.name==='schemes'?readFileSync(license,'utf8').split('License\n-------')[1]:readFileSync(license,'utf8')}\n\n`;
}
notices=notices.trimEnd()+'\n';
const noticeFile='plugins/n8r-surface/skills/research/scripts/THIRD-PARTY-NOTICES.txt';
if(process.argv.includes('--check')){if(readFileSync(noticeFile,'utf8')!==notices)throw Error('Stale third-party notices');}
else writeFileSync(noticeFile,notices);
