import {build} from 'esbuild';
import {readFileSync,writeFileSync} from 'node:fs';
const file='plugins/n8r-surface/skills/research/scripts/artifacts.mjs';
const result=await build({entryPoints:['src/skill-artifacts.ts'],bundle:true,platform:'node',format:'esm',target:'node22',write:false,legalComments:'inline',banner:{js:'// Generated by scripts/build-skill.mjs. Do not edit. See THIRD-PARTY-NOTICES.txt.\nimport {createRequire} from "node:module"; const require = createRequire(import.meta.url);'}});
const bytes=result.outputFiles[0].contents;
if(process.argv.includes('--check')){
 if(!readFileSync(file).equals(Buffer.from(bytes)))throw Error('Stale standalone skill bundle; run npm run build:skill');
}else writeFileSync(file,bytes);
